#!/usr/bin/env bash
# Provision a local development database and write .env (gitignored).
#
# Requires a PostgreSQL admin connection, e.g.:
#   PG_ADMIN_URL=postgres://postgres:postgres@127.0.0.1:5432/postgres scripts/dev-setup.sh # secret-scan:allow local-dev default for a throwaway local cluster
#
# Creates roles aegis_dev_owner (schema owner) and aegis_dev_app (runtime,
# member of the aegis_app group role) with freshly generated passwords, a
# database named aegis_dev, and runs migrations. Re-running rotates the
# passwords and rewrites .env. Never use this for production.
set -euo pipefail

ADMIN_URL="${PG_ADMIN_URL:-postgres://postgres:postgres@127.0.0.1:5432/postgres}" # secret-scan:allow local-dev default; override with PG_ADMIN_URL
DB_NAME="${AEGIS_DEV_DB:-aegis_dev}"
OWNER=aegis_dev_owner
APP=aegis_dev_app
ROOT="$(cd "$(dirname "$0")/.." && pwd)"

gen() { node -e "console.log(require('crypto').randomBytes(24).toString('base64url'))"; }
OWNER_PW="$(gen)"
APP_PW="$(gen)"

psql "$ADMIN_URL" -v ON_ERROR_STOP=1 -q \
  -v db_name="$DB_NAME" -v owner_role="$OWNER" -v owner_password="$OWNER_PW" \
  -v app_login="$APP" -v app_password="$APP_PW" \
  -f "$ROOT/apps/server/db/provision.sql"
# provision.sql only creates missing roles; rotate passwords so .env matches.
psql "$ADMIN_URL" -v ON_ERROR_STOP=1 -q \
  -v owner="$OWNER" -v owner_pw="$OWNER_PW" -v app="$APP" -v app_pw="$APP_PW" >/dev/null <<'SQL'
SELECT format('ALTER ROLE %I PASSWORD %L', :'owner', :'owner_pw') \gexec
SELECT format('ALTER ROLE %I PASSWORD %L', :'app', :'app_pw') \gexec
SQL

HOSTPORT="$(node -e "const u=new URL(process.argv[1]);console.log(u.host)" "$ADMIN_URL")"
umask 077
cat > "$ROOT/.env" <<ENV
# Generated by scripts/dev-setup.sh for LOCAL DEVELOPMENT ONLY. Do not commit.
AEGIS_ENV=development
APP_ORIGIN=http://localhost:5173
DATABASE_URL=postgres://$APP:$APP_PW@$HOSTPORT/$DB_NAME
DATABASE_MIGRATION_URL=postgres://$OWNER:$OWNER_PW@$HOSTPORT/$DB_NAME
SESSION_COOKIE_SECURE=false
LOG_LEVEL=info
WORKER_ENABLED=true
INTEGRATION_TEST_ADAPTER_ENABLED=true
INTEGRATION_ALLOW_PRIVATE_NETWORK=false
ENV

set -a; . "$ROOT/.env"; set +a
pnpm --filter @aegis/shared run build >/dev/null
(cd "$ROOT/apps/server" && npx tsx src/cli/migrate.ts)
echo "Development database ready. Next: pnpm --filter @aegis/server admin bootstrap --email you@example.com --name 'You' --tenant-slug dev --tenant-name 'Development'"
